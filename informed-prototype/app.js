const storyList = document.querySelector("#storyList");
const categoryTabs = document.querySelector("#categoryTabs");
const resultCount = document.querySelector("#resultCount");
const searchInput = document.querySelector("#searchInput");
const themeToggle = document.querySelector("#themeToggle");
const feedbackMessage = document.querySelector("#feedbackMessage");
const interestButton = document.querySelector("#interestButton");

const READ_MORE_LABEL = "Read more ›";
const COLLAPSE_LABEL = "Collapse ˅";

let activeCategory = "All";
let expandedStoryId = null;
const savedStoryIds = new Set();

function getCategories() {
  return ["All", ...new Set(stories.map((story) => story.category))];
}

function statusClass(status) {
  return status.toLowerCase().includes("developing") ? "developing" : "";
}

function visibleStories() {
  const searchTerm = searchInput.value.trim().toLowerCase();

  return stories.filter((story) => {
    const matchesCategory = activeCategory === "All" || story.category === activeCategory;
    const searchableText = [
      story.category,
      story.headline,
      story.status,
      story.summary,
      ...story.highlights,
      ...story.sources.map((source) => source.name)
    ]
      .join(" ")
      .toLowerCase();

    return matchesCategory && searchableText.includes(searchTerm);
  });
}

function renderCategoryTabs() {
  categoryTabs.innerHTML = getCategories()
    .map(
      (category) => `
        <button
          class="category-tab"
          type="button"
          aria-pressed="${category === activeCategory}"
          data-category="${category}"
        >
          ${category}
        </button>
      `
    )
    .join("");
}

function renderStories() {
  const matches = visibleStories();
  resultCount.textContent = `${matches.length} stor${matches.length === 1 ? "y" : "ies"}`;

  if (!matches.length) {
    storyList.innerHTML = `
      <p class="no-results">
        No sample story clusters match this filter. Try another category or search term.
      </p>
    `;
    return;
  }

  storyList.innerHTML = matches
    .map((story) => {
      const isExpanded = story.id === expandedStoryId;
      const readMoreButton = `
        <button
          class="read-button ${isExpanded ? "is-close" : ""}"
          type="button"
          aria-expanded="${isExpanded}"
          data-story-id="${story.id}"
        >
          ${isExpanded ? COLLAPSE_LABEL : READ_MORE_LABEL}
        </button>
      `;
      const saveButton = `
        <button
          class="save-button ${savedStoryIds.has(story.id) ? "is-saved" : ""}"
          type="button"
          aria-pressed="${savedStoryIds.has(story.id)}"
          aria-label="${savedStoryIds.has(story.id) ? "Remove bookmark" : "Bookmark story"}"
          title="${savedStoryIds.has(story.id) ? "Remove bookmark" : "Bookmark story"}"
          data-save-id="${story.id}"
        >
          <span class="bookmark-icon" aria-hidden="true"></span>
        </button>
      `;

      return `
        <article
          class="story-card ${isExpanded ? "is-expanded" : ""}"
          id="card-${story.id}"
        >
          <div class="card-topline">
            <span class="category">${story.category}</span>
            <span class="status-label ${statusClass(story.status)}">${story.status}</span>
          </div>
          <h3>${story.headline}</h3>
          <p class="freshness-line">
            <strong>Last updated:</strong>
            <span>${story.lastUpdated}</span>
            <span class="source-count">
              ${story.sourceCount} source${story.sourceCount === 1 ? "" : "s"}
            </span>
            <span class="metadata-actions">
              ${saveButton}
              ${readMoreButton}
            </span>
          </p>
          ${
            isExpanded
              ? `
                <div class="expanded-story" id="summary-${story.id}">
                  <section>
                    <h4>Summary</h4>
                    <p class="summary-text">${story.summary}</p>
                  </section>
                  <section>
                    <h4>Highlights</h4>
                    <ul class="detail-list">
                      ${story.highlights.map((detail) => `<li>${detail}</li>`).join("")}
                    </ul>
                  </section>
                  <section>
                    <h4>Sources</h4>
                    <p class="source-line" aria-label="Sources used">
                      ${story.sources
                        .map(
                          (source, index) => `
                            <a href="${source.url}" target="_blank" rel="noopener noreferrer">
                              ${source.name}
                            </a>${index < story.sources.length - 1 ? "<span aria-hidden=\"true\">&middot;</span>" : ""}
                          `
                        )
                        .join("")}
                    </p>
                  </section>
                </div>
              `
              : ""
          }
        </article>
      `;
    })
    .join("");
}

function toggleStory(storyId) {
  expandedStoryId = expandedStoryId === storyId ? null : storyId;
  renderStories();
}

function applyTheme(theme) {
  document.documentElement.dataset.theme = theme;
  const isDark = theme === "dark";
  themeToggle.textContent = isDark ? "Light" : "Dark";
  themeToggle.setAttribute("aria-pressed", String(isDark));
}

categoryTabs.addEventListener("click", (event) => {
  const button = event.target.closest("[data-category]");
  if (!button) return;

  activeCategory = button.dataset.category;
  expandedStoryId = null;
  renderCategoryTabs();
  renderStories();
});

storyList.addEventListener("click", (event) => {
  const saveButton = event.target.closest("[data-save-id]");
  if (saveButton) {
    const storyId = saveButton.dataset.saveId;
    if (savedStoryIds.has(storyId)) {
      savedStoryIds.delete(storyId);
    } else {
      savedStoryIds.add(storyId);
    }
    renderStories();
    return;
  }

  const trigger = event.target.closest("[data-story-id]");
  if (!trigger) return;

  event.preventDefault();
  toggleStory(trigger.dataset.storyId);
});

searchInput.addEventListener("input", () => {
  expandedStoryId = null;
  renderStories();
});

themeToggle.addEventListener("click", () => {
  const currentTheme = document.documentElement.dataset.theme === "dark" ? "dark" : "light";
  const nextTheme = currentTheme === "dark" ? "light" : "dark";
  applyTheme(nextTheme);
  localStorage.setItem("informed-prototype-theme", nextTheme);
});

